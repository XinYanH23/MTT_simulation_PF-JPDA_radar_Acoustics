function mc_write_seed_csv(csv_path, packs, names)
%MC_WRITE_SEED_CSV  每个种子一行：OSPA、基数、碎裂、IDS、虚警率、寿命。
%
%   packs : 1×C cell，每个元素为 mc_run_case 的 pack
%   names : 1×C cellstr 方案名

fid = fopen(csv_path, 'w', 'n', 'UTF-8');
fprintf(fid, ['seed,case,ospa_mean,ospa_loc_mean,ospa_card_mean,ospa_assign_mean,' ...
    'card_err_mean,fragmentation_count,' ...
    'id_switches,false_confirm_ratio,median_track_life,mean_track_life,' ...
    'peak_confirmed,ospa_rmse,pos_rmse\n']);
for c = 1:numel(packs)
    pk = packs{c};
    for i = 1:numel(pk.per_seed)
        m = pk.per_seed{i};
        fprintf(fid, ['%d,%s,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,' ...
            '%.6f,%.6f,%.6f,%.6f,%.6f,%.6f,%.6f\n'], ...
            m.seed, names{c}, m.ospa_mean, m.ospa_loc_mean, m.ospa_card_mean, ...
            m.ospa_assign_mean, m.card_err_mean, ...
            m.fragmentation_count, m.id_switches, m.false_confirm_ratio, ...
            m.median_track_life, m.mean_track_life, m.peak_confirmed, ...
            m.ospa_rmse, m.pos_rmse);
    end
end
fclose(fid);
end
