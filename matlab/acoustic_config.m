function cfg = acoustic_config()
%ACOUSTIC_CONFIG 声学概率场建模的统一参数配置（与 4SPL/config.py 对齐）。
%   返回一个 struct，所有可调参数集中于此。修改本文件即可做参数敏感性试验。
%
%   坐标系：与 config.py 一致，世界坐标单位 mm，[X, Y, Z]，Y 为高度方向。
%   概率场建立在固定高度 Y=src_height 的 X-Z 平面上。
%
%   参数来源标注：
%     [py]   = 4SPL/config.py（UAV-2 悬停标定，Lp = A - n*log10(r)，r 单位 m）
%     [docx] = 《四种方案对比.docx》2.4 节外场/室内动捕拟合
%     [sim]  = 仿真可调参数（无标定来源，用于敏感性研究）

cfg = struct();

% ---------------------------------------------------------------------
% 1. 麦克风节点几何与单点 SPL 标定参数  [py]
% ---------------------------------------------------------------------
% ── 与跟踪场景（run_scenario）坐标系对齐 ──────────────────────────────
% 跟踪场景：Urban, Map.size=1000m, acousticPos 由 greedySensorPlacement 生成
% 坐标系：X=East(mm), Y=Height(mm), Z=North(mm)
% 此处使用覆盖 1000×1000m 场景的典型麦克风布局（与贪婪算法对齐，可按实际 acousticPos 更新）
cfg.mic_ids = {'1', '2', '3', '4', '5', '6'};
cfg.mic_coords = [ ...
    150000, 1500, 150000;   % mic 1: (150m, 1.5m, 150m)
    150000, 1500, 850000;   % mic 2: (150m, 1.5m, 850m)
    500000, 1500,      0;   % mic 3: (500m, 1.5m,   0m)
    500000, 1500,1000000;   % mic 4: (500m, 1.5m,1000m)
    850000, 1500, 150000;   % mic 5: (850m, 1.5m, 150m)
    850000, 1500, 850000];  % mic 6: (850m, 1.5m, 850m)

% 传播模型参数（与标定节点一致，节点数扩展后统一用默认值）
cfg.A = repmat(-30.3, 6, 1);   % 均值 A (dB)
cfg.n = repmat(  8.7, 6, 1);   % 均值 n

% ---------------------------------------------------------------------
% 2. 传播与环境仿真参数  [sim]/[docx]
% ---------------------------------------------------------------------
cfg.alpha_atm   = 0.0;     % 大气吸收系数 (dB/m)，标准模型 Lp=A-n*log10(r)-alpha*r。默认0
cfg.ground_y_mm = 0.0;     % 地面平面 Y 坐标 (mm)，镜像源以此为对称面
cfg.R_ground    = 0.3;     % [sim] 地面反射系数 R∈[0,1]。0=自由场(还原标定模型)，1=全反射
                           %       非相干能量叠加：I_total = I_direct + R^2 * I_image
cfg.noise_floor_db = repmat(-50.0, 6, 1);    % 各节点环境底噪，与 mic 数量对齐

% ---------------------------------------------------------------------
% 3. 探测能力 P_D(SNR) — sigmoid  [sim]，参照 RIGOROUS 文档 §2
% ---------------------------------------------------------------------
cfg.det_eta_db   = 6.0;    % SNR 中点 (P_D=0.5 处)
cfg.det_kappa_db = 2.0;    % sigmoid 陡度
cfg.det_threshold = 0.5;   % 判定 detected 的 P_D 阈值

% ---------------------------------------------------------------------
% 4. 多节点融合（节点级 SNR 可靠性加权）  [sim]
% ---------------------------------------------------------------------
cfg.sigma0_db   = 3.0;     % 基准量测噪声标准差 (dB)，对应 probability_grid.py 的 sigma_db
cfg.beta_snr    = 0.15;    % 异方差膨胀系数：sigma_m=sigma0*exp(beta*max(0,snr_ref-snr_m))
cfg.snr_ref_db  = 6.0;     % 异方差/温度参考 SNR
cfg.weight_tau  = 6.0;     % 节点可靠性 softmax 温度 (dB)：w_m ∝ exp(snr_m/weight_tau)

% ---------------------------------------------------------------------
% 5. 概率场网格  [sim]
% ---------------------------------------------------------------------
cfg.src_height_mm  = 30000.0;   % 飞行高度约 30m（与 Urban 场景 zlim 中心对齐）
cfg.grid_margin_mm = 50000.0;   % 网格在麦克风包络外扩展（50m，覆盖边界目标）
cfg.grid_res_mm    = 10000.0;   % 网格分辨率 10m（1000m 场景下约 100×100 格）

% ---------------------------------------------------------------------
% 6. 三种似然映射方法参数  [docx]
% ---------------------------------------------------------------------
% 方案一：温度 Softmax（玻尔兹曼分布），tau 随 SNR 动态
cfg.softmax_tau0   = 1.0;       % 基准温度
cfg.softmax_tau_c  = 0.20;      % SNR 退化时的温度放大系数：tau=tau0*exp(c*max(0,snr_ref-snr_bar))
% 方案二：能量域 [I - I_noise]^alpha
cfg.intensity_alpha   = 1.0;    % 对比度调节因子
cfg.intensity_I_noise = 0.0;    % 归一化能量域的底噪基准（相对 [0,1] 标度）
% 方案三：NMS Top-K 峰值 + 核混合
cfg.nms_K        = 3;           % 保留的局部峰值数
cfg.nms_min_dist = 2;           % NMS 峰值间最小格距（抑制旁瓣）
cfg.nms_kernel   = 'gaussian';  % 'gaussian' | 'epanechnikov' | 'laplacian'
cfg.nms_sigma_mm = 800.0;       % 核宽度（基准，随噪声缩放）
cfg.nms_sigma_snr_scale = 0.10; % 低 SNR 时核宽放大系数

% ---------------------------------------------------------------------
% 7. 递归贝叶斯滤波（Chapman-Kolmogorov 扩散 + 熵门控）  [docx]
% ---------------------------------------------------------------------
cfg.bayes_diffusion_mm = 600.0; % 随机游走扩散标准差 (mm)，对应预测步空间不确定度
cfg.bayes_entropy_gate = 0.95;  % 归一化似然熵阈值（>阈值则跳过更新）。设为 Inf 表示永不跳过

% ---------------------------------------------------------------------
% 8. 麦克风布局优化（贪婪算法）  [sim]
% ---------------------------------------------------------------------
% 覆盖评估区域（X-Z 平面，mm）；空矩阵 [] 则用麦克风包络 + grid_margin_mm 自动推断
cfg.placement_area_mm   = [0, 1e6, 0, 1e6];  % 跟踪场景范围 [0,1000m] x [0,1000m] (mm)
cfg.placement_area_res_mm = 20000.0;         % 覆盖评估分辨率 20m
% 停止准则：满足覆盖率或达到节点数上限，两者以先满足者为准
cfg.placement_min_coverage = 0.80; % 全域平均 P_D_joint 目标阈值（0~1）
cfg.placement_max_nodes    = 8;    % 节点数上限（预算约束）
% 覆盖率计算用的 P_D "已覆盖" 判定门限（通常与 det_threshold 一致）
cfg.placement_pd_threshold = 0.5;  % P_D_joint >= 此值的格点计为"已覆盖"
% 候选节点的默认传播参数（若未逐节点提供则使用此默认值）[sim]
cfg.placement_A_default  = -30.3;  % 均值 A (dB)，参考三个标定麦克风均值
cfg.placement_n_default  =   8.7;  % 均值 n，同上
cfg.placement_nf_default = -50.0;  % 候选节点默认环境底噪 (dB)

end
